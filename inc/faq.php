if (! function_exists('romonet_get_faq_popular_items')) {
  function romonet_get_faq_popular_items()
  {
    $popular = array();

    foreach (romonet_get_faq_categories() as $category) {
      foreach ($category['items'] as $index => $item) {
        if (! empty($item['popular'])) {
          $popular[] = array(
            'id'       => $category['id'] . '-' . $index,
            'question' => $item['question'],
            'category' => $category['id'],
          );
        }
      }
    }

    return $popular;
  }
}

